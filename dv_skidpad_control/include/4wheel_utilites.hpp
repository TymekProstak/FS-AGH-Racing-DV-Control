inline TorqueAllocationMode selectTorqueAllocationMode(
    const ParamBank& P
)
{
    const bool assume_dv_qp =
        paramFlag(
            P,
            "general.assume_dv_qp_torque_allocation"
        );

    const bool assume_dv_axle =
        paramFlag(
            P,
            "general.assume_dv_axle_torque_allocation"
        );

    const bool assume_jaca =
        paramFlag(
            P,
            "general.assume_jaca_torque_allocation"
        );

    const int selected_count =
        static_cast<int>(assume_dv_qp)
        + static_cast<int>(assume_dv_axle)
        + static_cast<int>(assume_jaca);

    if (selected_count != 1)
    {
        throw std::runtime_error(
            "Exactly one torque allocation mode must be enabled: "
            "general.assume_dv_qp_torque_allocation, "
            "general.assume_dv_axle_torque_allocation, "
            "general.assume_jaca_torque_allocation"
        );
    }

    if (assume_dv_qp)
    {
        return TorqueAllocationMode::DV_QP;
    }

    if (assume_dv_axle)
    {
        return TorqueAllocationMode::DV_AXLE;
    }

    return TorqueAllocationMode::JACA;
}

// ============================================================================
//                          BASE TORQUE ALLOCATION
// ============================================================================

inline WheelValues allocateBaseTorqueJacaNm(
    const ParamBank& P,
    const double total_torque_Nm
)
{
    const bool is_drive =
        total_torque_Nm >= 0.0;

    const double front_fraction_raw =
        is_drive
        ? P.get("general.jaca_front_torque_fraction_drive")
        : P.get("general.jaca_front_torque_fraction_brake");

    const double front_fraction =
        clampLocal(
            front_fraction_raw,
            0.0,
            1.0
        );

    const double rear_fraction =
        1.0 - front_fraction;

    WheelValues torque;

    torque.FL =
        0.5 * front_fraction * total_torque_Nm;

    torque.FR =
        0.5 * front_fraction * total_torque_Nm;

    torque.RL =
        0.5 * rear_fraction * total_torque_Nm;

    torque.RR =
        0.5 * rear_fraction * total_torque_Nm;

    return torque;
}

inline WheelValues allocateBaseTorqueDvAxleNm(
    const double total_torque_Nm,
    const WheelValues& Fz_N
)
{
    /*
        DV axle allocation:

        1. left side gets 50% total torque.
        2. right side gets 50% total torque.
        3. inside each side, front/rear split is proportional to Fz.

        This keeps base allocation neutral in left/right.
    */

    const double left_total_Nm =
        0.5 * total_torque_Nm;

    const double right_total_Nm =
        0.5 * total_torque_Nm;

    const double left_Fz_sum =
        std::max(
            1.0,
            Fz_N.FL + Fz_N.RL
        );

    const double right_Fz_sum =
        std::max(
            1.0,
            Fz_N.FR + Fz_N.RR
        );

    WheelValues torque;

    torque.FL =
        left_total_Nm
        * Fz_N.FL / left_Fz_sum;

    torque.RL =
        left_total_Nm
        * Fz_N.RL / left_Fz_sum;

    torque.FR =
        right_total_Nm
        * Fz_N.FR / right_Fz_sum;

    torque.RR =
        right_total_Nm
        * Fz_N.RR / right_Fz_sum;

    return torque;
}

// ============================================================================
//                      YAW MOMENT FROM WHEEL TORQUES
// ============================================================================
//
// Wheel force variable:
//      Fx_i = torque_i / R_tire
//
// Front wheels are steered:
//
//      Fx_body = Fx_wheel * cos(delta)
//      Fy_body = Fx_wheel * sin(delta)
//
// Moment:
//
//      Mz = x * Fy - y * Fx
//
// ============================================================================

inline double computeYawMomentFromWheelTorquesNm(
    const ParamBank& P,
    const WheelValues& torque_Nm,
    const double delta_left_rad,
    const double delta_right_rad
)
{
    const double l_f =
        P.get("model.body.l_f");

    const double half_track =
        0.5 * getTrackWidthM(P);

    const double R_tire =
        getTireRadiusM(P);

    const double Fx_FL =
        torque_Nm.FL / safeAbs(R_tire);

    const double Fx_FR =
        torque_Nm.FR / safeAbs(R_tire);

    const double Fx_RL =
        torque_Nm.RL / safeAbs(R_tire);

    const double Fx_RR =
        torque_Nm.RR / safeAbs(R_tire);

    const double Fx_FL_body =
        Fx_FL * std::cos(delta_left_rad);

    const double Fy_FL_body =
        Fx_FL * std::sin(delta_left_rad);

    const double Fx_FR_body =
        Fx_FR * std::cos(delta_right_rad);

    const double Fy_FR_body =
        Fx_FR * std::sin(delta_right_rad);

    const double Mz_FL =
        l_f * Fy_FL_body
        - half_track * Fx_FL_body;

    const double Mz_FR =
        l_f * Fy_FR_body
        + half_track * Fx_FR_body;

    const double Mz_RL =
        -half_track * Fx_RL;

    const double Mz_RR =
        half_track * Fx_RR;

    return
        Mz_FL
        + Mz_FR
        + Mz_RL
        + Mz_RR;
}

// ============================================================================
//                          DV AXLE TV
// ============================================================================

inline WheelValues applyDvAxleTorqueVectoringNm(
    const WheelValues& base_torque_Nm,
    const double delta_front_tv_Nm,
    const double delta_rear_tv_Nm
)
{
    WheelValues out =
        base_torque_Nm;

    /*
        DV axle:
            tau = tau_base + [dTauF, -dTauF, dTauR, -dTauR]
    */

    out.FL += delta_front_tv_Nm;
    out.FR -= delta_front_tv_Nm;

    out.RL += delta_rear_tv_Nm;
    out.RR -= delta_rear_tv_Nm;

    return out;
}

inline void computeDvAxleTorqueVectoringDeltasForYawMoment(
    const ParamBank& P,
    const WheelValues& Fz_N,
    const double tv_yaw_moment_target_Nm,
    const double delta_left_rad,
    const double delta_right_rad,
    double& delta_front_tv_Nm,
    double& delta_rear_tv_Nm
)
{
    const double R_tire =
        getTireRadiusM(P);

    const double l_f =
        P.get("model.body.l_f");

    const double track =
        getTrackWidthM(P);

    const double half_track =
        0.5 * track;

    /*
        Influence of [dTauF, -dTauF] on yaw moment.
    */

    const double coeff_front =
        (
            l_f * (
                std::sin(delta_left_rad)
                - std::sin(delta_right_rad)
            )
            - half_track * (
                std::cos(delta_left_rad)
                + std::cos(delta_right_rad)
            )
        )
        / safeAbs(R_tire);

    /*
        Influence of [dTauR, -dTauR] on yaw moment.
    */

    const double coeff_rear =
        -track / safeAbs(R_tire);

    const double Fz_front =
        Fz_N.FL + Fz_N.FR;

    const double Fz_rear =
        Fz_N.RL + Fz_N.RR;

    const double Fz_total =
        std::max(
            1.0,
            Fz_front + Fz_rear
        );

    const double front_tv_share =
        Fz_front / Fz_total;

    const double rear_tv_share =
        Fz_rear / Fz_total;

    const double yaw_moment_per_lambda =
        coeff_front * front_tv_share
        + coeff_rear * rear_tv_share;

    if (std::abs(yaw_moment_per_lambda) < 1.0e-9)
    {
        delta_front_tv_Nm = 0.0;
        delta_rear_tv_Nm = 0.0;
        return;
    }

    const double lambda =
        tv_yaw_moment_target_Nm / yaw_moment_per_lambda;

    delta_front_tv_Nm =
        lambda * front_tv_share;

    delta_rear_tv_Nm =
        lambda * rear_tv_share;
}

// ============================================================================
//                          JACA TV
// ============================================================================

inline WheelValues applyJacaTorqueVectoringNm(
    const WheelValues& base_torque_Nm,
    const double delta_jaca_tv_Nm
)
{
    WheelValues out =
        base_torque_Nm;

    /*
        JACA:
            tau = tau_base + [dTauJ, -dTauJ, dTauJ, -dTauJ]

        No additional front/rear balance inside TV.
        Front/rear balance is only in base allocation.
    */

    out.FL += delta_jaca_tv_Nm;
    out.FR -= delta_jaca_tv_Nm;

    out.RL += delta_jaca_tv_Nm;
    out.RR -= delta_jaca_tv_Nm;

    return out;
}

inline double computeJacaTorqueVectoringDeltaForYawMoment(
    const ParamBank& P,
    const double tv_yaw_moment_target_Nm,
    const double delta_left_rad,
    const double delta_right_rad
)
{
    const double R_tire =
        getTireRadiusM(P);

    const double l_f =
        P.get("model.body.l_f");

    const double track =
        getTrackWidthM(P);

    const double half_track =
        0.5 * track;

    const double coeff_front =
        (
            l_f * (
                std::sin(delta_left_rad)
                - std::sin(delta_right_rad)
            )
            - half_track * (
                std::cos(delta_left_rad)
                + std::cos(delta_right_rad)
            )
        )
        / safeAbs(R_tire);

    const double coeff_rear =
        -track / safeAbs(R_tire);

    const double coeff_jaca =
        coeff_front
        + coeff_rear;

    if (std::abs(coeff_jaca) < 1.0e-9)
    {
        return 0.0;
    }

    return
        tv_yaw_moment_target_Nm / coeff_jaca;
}

// ============================================================================
//                          DV QP ALLOCATION
// ============================================================================
//
// u = [Fx_FL, Fx_FR, Fx_RL, Fx_RR]^T
//
// G*u = [Fx_body_total, Mz_total]^T
//
// Corrected G:
//
// Fx row:
//      FL: cos(delta_left)
//      FR: cos(delta_right)
//      RL: 1
//      RR: 1
//
// Mz row:
//      FL: l_f*sin(delta_left)  - track/2*cos(delta_left)
//      FR: l_f*sin(delta_right) + track/2*cos(delta_right)
//      RL: -track/2
//      RR: +track/2
//
// Cost:
//
//      J = (G*u - target)^T Q (G*u - target) + u^T R u
//
// R penalizes low-Fz wheels more:
//
//      r_i = lambda * Fz_total/Fz_i * qFx
//
// Parametry wymagane:
//      general.torque_allocation_lambda_factor
//      general.torque_allocation_fx_ref
//      general.torque_allocation_mz_ref
//
// ============================================================================

inline bool solveDvQpWheelForcesN(
    const ParamBank& P,
    const WheelValues& Fz_N,
    const double fx_target_N,
    const double mz_target_Nm,
    const double delta_left_rad,
    const double delta_right_rad,
    WheelValues& wheel_forces_N
)
{
    const double l_f =
        P.get("model.body.l_f");

    const double track =
        getTrackWidthM(P);

    const double half_track =
        0.5 * track;

    const double Fx_ref =
        P.get("general.torque_allocation_fx_ref");

    const double Mz_ref =
        P.get("general.torque_allocation_mz_ref");

    const double lambda =
        P.get("general.torque_allocation_lambda_factor");

    const double qFx =
        1.0 / (safeAbs(Fx_ref) * safeAbs(Fx_ref));

    const double qMz =
        1.0 / (safeAbs(Mz_ref) * safeAbs(Mz_ref));

    Eigen::Matrix<double, 2, 4> G;

    G <<
        std::cos(delta_left_rad),
        std::cos(delta_right_rad),
        1.0,
        1.0,

        l_f * std::sin(delta_left_rad) - half_track * std::cos(delta_left_rad),
        l_f * std::sin(delta_right_rad) + half_track * std::cos(delta_right_rad),
        -half_track,
        +half_track;

    Eigen::Matrix2d Q =
        Eigen::Matrix2d::Zero();

    Q(0, 0) =
        qFx;

    Q(1, 1) =
        qMz;

    const double Fz_total =
        std::max(
            1.0,
            Fz_N.FL
            + Fz_N.FR
            + Fz_N.RL
            + Fz_N.RR
        );

    Eigen::Matrix4d R =
        Eigen::Matrix4d::Zero();

    R(0, 0) =
        lambda
        * Fz_total / std::max(1.0, Fz_N.FL)
        * qFx;

    R(1, 1) =
        lambda
        * Fz_total / std::max(1.0, Fz_N.FR)
        * qFx;

    R(2, 2) =
        lambda
        * Fz_total / std::max(1.0, Fz_N.RL)
        * qFx;

    R(3, 3) =
        lambda
        * Fz_total / std::max(1.0, Fz_N.RR)
        * qFx;

    Eigen::Vector2d target;

    target <<
        fx_target_N,
        mz_target_Nm;

    const Eigen::Matrix4d A =
        G.transpose() * Q * G
        + R;

    const Eigen::Vector4d c =
        G.transpose() * Q * target;

    Eigen::LLT<Eigen::Matrix4d> llt(A);

    if (llt.info() != Eigen::Success)
    {
        return false;
    }

    const Eigen::Vector4d u =
        llt.solve(c);

    if (llt.info() != Eigen::Success || !u.allFinite())
    {
        return false;
    }

    wheel_forces_N.FL = u(0);
    wheel_forces_N.FR = u(1);
    wheel_forces_N.RL = u(2);
    wheel_forces_N.RR = u(3);

    return true;
}

