inline double computeGlobalTorqueScaleFromWheelLimits(
    const WheelValues& torque_after_tv_Nm,
    const WheelValues& max_abs_torque_Nm
)
{
    double scale =
        1.0;

    if (std::abs(torque_after_tv_Nm.FL) > 1.0e-9)
    {
        scale =
            std::min(
                scale,
                max_abs_torque_Nm.FL
                / std::abs(torque_after_tv_Nm.FL)
            );
    }

    if (std::abs(torque_after_tv_Nm.FR) > 1.0e-9)
    {
        scale =
            std::min(
                scale,
                max_abs_torque_Nm.FR
                / std::abs(torque_after_tv_Nm.FR)
            );
    }

    if (std::abs(torque_after_tv_Nm.RL) > 1.0e-9)
    {
        scale =
            std::min(
                scale,
                max_abs_torque_Nm.RL
                / std::abs(torque_after_tv_Nm.RL)
            );
    }

    if (std::abs(torque_after_tv_Nm.RR) > 1.0e-9)
    {
        scale =
            std::min(
                scale,
                max_abs_torque_Nm.RR
                / std::abs(torque_after_tv_Nm.RR)
            );
    }

    return clampLocal(
        scale,
        0.0,
        1.0
    );
}

inline double computeScaleForOneSignedWheelTorqueLimit(
    const double torque_Nm,
    const double drive_limit_Nm,
    const double brake_limit_Nm
)
{
    constexpr double EPS =
        1.0e-9;

    if (std::abs(torque_Nm) <= EPS)
    {
        return 1.0;
    }

    const double limit_Nm =
        torque_Nm >= 0.0
            ? drive_limit_Nm
            : brake_limit_Nm;

    return
        std::max(0.0, limit_Nm)
        / std::abs(torque_Nm);
}

inline double computeGlobalScaleFromPerWheelEngineLimits(
    const WheelValues& torque_Nm,
    const double drive_limit_Nm,
    const double brake_limit_Nm
)
{
    double scale =
        1.0;

    scale =
        std::min(
            scale,
            computeScaleForOneSignedWheelTorqueLimit(
                torque_Nm.FL,
                drive_limit_Nm,
                brake_limit_Nm
            )
        );

    scale =
        std::min(
            scale,
            computeScaleForOneSignedWheelTorqueLimit(
                torque_Nm.FR,
                drive_limit_Nm,
                brake_limit_Nm
            )
        );

    scale =
        std::min(
            scale,
            computeScaleForOneSignedWheelTorqueLimit(
                torque_Nm.RL,
                drive_limit_Nm,
                brake_limit_Nm
            )
        );

    scale =
        std::min(
            scale,
            computeScaleForOneSignedWheelTorqueLimit(
                torque_Nm.RR,
                drive_limit_Nm,
                brake_limit_Nm
            )
        );

    return clampLocal(
        scale,
        0.0,
        1.0
    );
}

// ============================================================================
//                              MAIN FUNCTION
// ============================================================================

inline TorqueAllocationResult allocateWheelTorquesForDvControl(
    const ParamBank& P,
    const TorqueAllocationInput& input
)
{
    TorqueAllocationResult result;

    result.mode =
        selectTorqueAllocationMode(P);

    result.input_total_torque_cmd_Nm =
        input.total_torque_cmd_Nm;

    result.previous_total_limited_torque_Nm =
        input.previous_total_limited_torque_valid
            ? input.previous_total_limited_torque_Nm
            : 0.0;

    result.normalized_M_dot_up =
        getNormalizedTorqueRateUp(P);

    result.normalized_M_dot_down =
        getNormalizedTorqueRateDown(P);

    const double allocator_dt_s =
        getControlDtForTorqueAllocator(P);

    result.max_total_torque_step_up_Nm =
        result.normalized_M_dot_up
        * getMaxTotalWheelTorqueNm(P)
        * allocator_dt_s;

    result.max_total_torque_step_down_Nm =
        result.normalized_M_dot_down
        * getMaxTotalWheelTorqueNm(P)
        * allocator_dt_s;

    result.torque_rate_limiter_bypassed =
        input.bypass_torque_rate_limiter;

    if (result.torque_rate_limiter_bypassed)
    {
        result.rate_limited_total_torque_cmd_Nm =
            input.total_torque_cmd_Nm;
    }
    else
    {
        result.rate_limited_total_torque_cmd_Nm =
            clampTotalTorqueByRateLimiterNm(
                input.total_torque_cmd_Nm,
                result.previous_total_limited_torque_Nm,
                result.max_total_torque_step_up_Nm,
                result.max_total_torque_step_down_Nm
            );
    }

    const double total_torque_cmd_after_input_rate_limit_Nm =
        result.rate_limited_total_torque_cmd_Nm;

    const bool input_total_torque_rate_limited =
        std::abs(
            result.rate_limited_total_torque_cmd_Nm
            - input.total_torque_cmd_Nm
        ) > 1.0e-6;

    result.vx_raw_mps =
        input.vx_mps;

    result.vx_for_slip_limiter_mps =
        speedForSlipAndLimiterMps(
            input.vx_mps
        );

    result.requested_yaw_moment_Nm =
        input.desired_yaw_moment_Nm;

    result.requested_longitudinal_force_N =
        wheelTorqueToFxN(
            P,
            total_torque_cmd_after_input_rate_limit_Nm
        );

    const SteeringAngles steering_angles =
        computeAntiAckermannSteeringAngles(
            input.delta_bicycle_rad,
            P
        );

    const double delta_left_rad =
        steering_angles.delta_left_rad;

    const double delta_right_rad =
        steering_angles.delta_right_rad;

    result.delta_left_rad =
        delta_left_rad;

    result.delta_right_rad =
        delta_right_rad;

    /*
        1. Estimate normal loads.
    */

    result.Fz_N =
        estimateWheelNormalLoadsN(
            P,
            input.ax_mps2,
            input.ay_mps2,
            input.vx_mps
        );

    /*
        2. Estimate slip angles like tire model.
    */

    result.slip_angle_rad =
        estimateWheelSlipAnglesLikeTireModelRad(
            P,
            result.vx_for_slip_limiter_mps,
            input.vy_mps,
            input.yaw_rate_radps,
            delta_left_rad,
            delta_right_rad
        );

    /*
        3. Estimate lateral forces for friction pre-limiter.
    */

    result.estimated_Fy_N =
        estimateWheelLateralForcesFromSlipAnglesN(
            P,
            result.slip_angle_rad,
            result.Fz_N
        );

    /*
        4. Torque allocation.
    */

    if (result.mode == TorqueAllocationMode::JACA)
    {
        result.torque_base_Nm =
            allocateBaseTorqueJacaNm(
                P,
                total_torque_cmd_after_input_rate_limit_Nm
            );

        result.base_yaw_moment_Nm =
            computeYawMomentFromWheelTorquesNm(
                P,
                result.torque_base_Nm,
                delta_left_rad,
                delta_right_rad
            );

        result.tv_yaw_moment_target_Nm =
            input.desired_yaw_moment_Nm;

        result.delta_jaca_tv_Nm =
            computeJacaTorqueVectoringDeltaForYawMoment(
                P,
                result.tv_yaw_moment_target_Nm,
                delta_left_rad,
                delta_right_rad
            );

        result.torque_after_tv_Nm =
            applyJacaTorqueVectoringNm(
                result.torque_base_Nm,
                result.delta_jaca_tv_Nm
            );
    }
    else if (result.mode == TorqueAllocationMode::DV_AXLE)
    {
        result.torque_base_Nm =
            allocateBaseTorqueDvAxleNm(
                total_torque_cmd_after_input_rate_limit_Nm,
                result.Fz_N
            );

        result.base_yaw_moment_Nm =
            computeYawMomentFromWheelTorquesNm(
                P,
                result.torque_base_Nm,
                delta_left_rad,
                delta_right_rad
            );

        result.tv_yaw_moment_target_Nm =
            input.desired_yaw_moment_Nm;

        computeDvAxleTorqueVectoringDeltasForYawMoment(
            P,
            result.Fz_N,
            result.tv_yaw_moment_target_Nm,
            delta_left_rad,
            delta_right_rad,
            result.delta_front_tv_Nm,
            result.delta_rear_tv_Nm
        );

        result.torque_after_tv_Nm =
            applyDvAxleTorqueVectoringNm(
                result.torque_base_Nm,
                result.delta_front_tv_Nm,
                result.delta_rear_tv_Nm
            );
    }
    else
    {
        /*
            DV_QP mode.

            QP directly solves wheel forces for:
                Fx_target,
                Mz_target.

            torque_base_Nm is only debug/reference.
        */

        result.torque_base_Nm =
            allocateBaseTorqueDvAxleNm(
                total_torque_cmd_after_input_rate_limit_Nm,
                result.Fz_N
            );

        result.base_yaw_moment_Nm =
            computeYawMomentFromWheelTorquesNm(
                P,
                result.torque_base_Nm,
                delta_left_rad,
                delta_right_rad
            );

        result.tv_yaw_moment_target_Nm =
            input.desired_yaw_moment_Nm;

        const double fx_target_N =
            result.requested_longitudinal_force_N;

        WheelValues wheel_forces_N;

        result.qp_solved =
            solveDvQpWheelForcesN(
                P,
                result.Fz_N,
                fx_target_N,
                input.desired_yaw_moment_Nm,
                delta_left_rad,
                delta_right_rad,
                wheel_forces_N
            );

        if (result.qp_solved)
        {
            result.torque_after_tv_Nm =
                wheelForcesToTorquesNm(
                    P,
                    wheel_forces_N
                );

            computeEquivalentTvDeltasForDebug(
                result.torque_base_Nm,
                result.torque_after_tv_Nm,
                result.delta_front_tv_Nm,
                result.delta_rear_tv_Nm
            );
        }
        else
        {
            /*
                Fallback:
                    DV_AXLE base + DV_AXLE TV.

                Nadal bez defaultów parametrów.
            */

            result.used_fallback =
                true;

            computeDvAxleTorqueVectoringDeltasForYawMoment(
                P,
                result.Fz_N,
                result.tv_yaw_moment_target_Nm,
                delta_left_rad,
                delta_right_rad,
                result.delta_front_tv_Nm,
                result.delta_rear_tv_Nm
            );

            result.torque_after_tv_Nm =
                applyDvAxleTorqueVectoringNm(
                    result.torque_base_Nm,
                    result.delta_front_tv_Nm,
                    result.delta_rear_tv_Nm
                );
        }
    }

    result.achieved_yaw_moment_before_limit_Nm =
        computeYawMomentFromWheelTorquesNm(
            P,
            result.torque_after_tv_Nm,
            delta_left_rad,
            delta_right_rad
        );

    result.achieved_longitudinal_force_before_limit_N =
        computeLongitudinalBodyForceFromWheelTorquesN(
            P,
            result.torque_after_tv_Nm,
            delta_left_rad,
            delta_right_rad
        );

    result.yaw_moment_error_before_limit_Nm =
        result.tv_yaw_moment_target_Nm
        - result.achieved_yaw_moment_before_limit_Nm;

    result.longitudinal_force_error_before_limit_N =
        result.requested_longitudinal_force_N
        - result.achieved_longitudinal_force_before_limit_N;

    result.total_torque_after_tv_Nm =
        sumWheelValues(
            result.torque_after_tv_Nm
        );

    /*
        5. Global scale limiter after final torque_after_tv.
    */

    const bool use_friction_ellipse =
        paramFlag(
            P,
            "general.use_friction_elipse_limiter"
        );

    const WheelValues mechanical_limit =
        getMaxAbsWheelTorqueMechanicalNm(P);

    constexpr double FRICTION_ELLIPSE_MIN_SPEED_MPS =
        3.0;

    const bool friction_ellipse_speed_active =
        std::abs(input.vx_mps) > FRICTION_ELLIPSE_MIN_SPEED_MPS;

    /*
        Mechanical torque limits are always active.

        Friction ellipse is active only above 3 m/s real vehicle speed.
        Below that, slip/Fy estimation is too noisy and too artificial because
        vx_for_slip_limiter_mps is deliberately floored to 2 m/s only to avoid
        singular slip-angle calculation at standstill.
    */
    if (use_friction_ellipse && friction_ellipse_speed_active)
    {
        result.max_abs_torque_from_friction_Nm =
            computeMaxAbsWheelTorqueFromFrictionEllipseNm(
                P,
                result.Fz_N,
                result.estimated_Fy_N
            );

        result.max_abs_torque_after_all_limits_Nm =
            minWheelValues(
                mechanical_limit,
                result.max_abs_torque_from_friction_Nm
            );
    }
    else
    {
        result.max_abs_torque_from_friction_Nm =
            mechanical_limit;

        result.max_abs_torque_after_all_limits_Nm =
            mechanical_limit;
    }

    result.hard_limit_scale =
        computeGlobalTorqueScaleFromWheelLimits(
            result.torque_after_tv_Nm,
            result.max_abs_torque_after_all_limits_Nm
        );

    if (result.torque_rate_limiter_bypassed)
    {
        result.total_torque_rate_scale_min =
            0.0;

        result.total_torque_rate_scale_max =
            std::numeric_limits<double>::infinity();

        result.total_torque_rate_limited_scale =
            1.0;

        result.torque_rate_limited =
            false;

        result.torque_rate_forced_over_hard_limit =
            false;

        result.global_scale =
            result.hard_limit_scale;
    }
    else
    {
        result.total_torque_rate_scale_min =
            computeTotalTorqueRateScaleMin(
                result.previous_total_limited_torque_Nm,
                result.total_torque_after_tv_Nm,
                result.max_total_torque_step_up_Nm,
                result.max_total_torque_step_down_Nm
            );

        result.total_torque_rate_scale_max =
            computeTotalTorqueRateScaleMax(
                result.previous_total_limited_torque_Nm,
                result.total_torque_after_tv_Nm,
                result.max_total_torque_step_up_Nm,
                result.max_total_torque_step_down_Nm
            );

        result.total_torque_rate_limited_scale =
            clampLocal(
                1.0,
                result.total_torque_rate_scale_min,
                result.total_torque_rate_scale_max
            );

        result.global_scale =
            clampLocal(
                result.hard_limit_scale,
                result.total_torque_rate_scale_min,
                result.total_torque_rate_scale_max
            );

        result.torque_rate_forced_over_hard_limit =
            result.global_scale > result.hard_limit_scale + 1.0e-9;

        result.torque_rate_limited =
            input_total_torque_rate_limited
            || std::abs(
                result.total_torque_rate_limited_scale - 1.0
            ) > 1.0e-6
            || result.torque_rate_forced_over_hard_limit;
    }

    result.limited =
        std::abs(result.global_scale - 1.0) > 1.0e-6;

    result.torque_limited_Nm =
        scaleWheelValues(
            result.torque_after_tv_Nm,
            result.global_scale
        );

    /*
        6. Final per-wheel engine-side torque limiter.

        This is intentionally applied after all other limiters.

        It checks the final wheel torques against engine-side per-wheel limits
        converted to wheel side:

            drive wheel limit = wheel_max_torque_engine_drive_Nm * gear_ratio
            brake wheel limit = wheel_max_torque_engine_brake_Nm * gear_ratio

        One global scale is applied to all four wheels, so base allocation and
        TV balance are preserved.
    */

    result.wheel_drive_limit_from_engine_Nm =
        getWheelDriveLimitFromEngineNm(P);

    result.wheel_brake_limit_from_engine_Nm =
        getWheelBrakeLimitFromEngineNm(P);

    result.final_engine_per_wheel_limit_scale =
        computeGlobalScaleFromPerWheelEngineLimits(
            result.torque_limited_Nm,
            result.wheel_drive_limit_from_engine_Nm,
            result.wheel_brake_limit_from_engine_Nm
        );

    result.final_engine_per_wheel_limited =
        std::abs(
            result.final_engine_per_wheel_limit_scale
            - 1.0
        ) > 1.0e-6;

    if (result.final_engine_per_wheel_limited)
    {
        result.torque_limited_Nm =
            scaleWheelValues(
                result.torque_limited_Nm,
                result.final_engine_per_wheel_limit_scale
            );

        result.global_scale *=
            result.final_engine_per_wheel_limit_scale;
    }

    result.limited =
        result.limited
        || result.final_engine_per_wheel_limited;

    result.achieved_yaw_moment_after_limit_Nm =
        computeYawMomentFromWheelTorquesNm(
            P,
            result.torque_limited_Nm,
            delta_left_rad,
            delta_right_rad
        );

    result.achieved_longitudinal_force_after_limit_N =
        computeLongitudinalBodyForceFromWheelTorquesN(
            P,
            result.torque_limited_Nm,
            delta_left_rad,
            delta_right_rad
        );

    result.yaw_moment_error_after_limit_Nm =
        result.tv_yaw_moment_target_Nm
        - result.achieved_yaw_moment_after_limit_Nm;

    result.longitudinal_force_error_after_limit_N =
        result.requested_longitudinal_force_N
        - result.achieved_longitudinal_force_after_limit_N;

    result.total_torque_limited_Nm =
        sumWheelValues(
            result.torque_limited_Nm
        );

    return result;
}

