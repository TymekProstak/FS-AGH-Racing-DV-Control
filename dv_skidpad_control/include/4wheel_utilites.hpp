struct WheelValues
{
    double FL = 0.0;
    double FR = 0.0;
    double RL = 0.0;
    double RR = 0.0;
};

enum class TorqueAllocationMode
{
    DV_QP,
    DV_AXLE,
    JACA
};

struct TorqueAllocationInput
{
    /*
        Suma momentów na wszystkich kołach.

        total_torque_cmd_Nm > 0  -> drive
        total_torque_cmd_Nm < 0  -> brake
    */
    double total_torque_cmd_Nm = 0.0;

    /*
        Target yaw moment generated by longitudinal wheel forces.

        In DV_QP:
            QP directly tries to achieve this Mz.

        In DV_AXLE/JACA:
            this value is interpreted directly as the yaw moment target
            for torque vectoring itself. We do not subtract base_yaw_moment_Nm.
    */
    double desired_yaw_moment_Nm = 0.0;

    /*
        Vehicle velocity in body frame.
    */
    double vx_mps = 0.0;
    double vy_mps = 0.0;
    double yaw_rate_radps = 0.0;

    /*
        Acceleration estimate for normal load estimation.

        ax > 0 -> acceleration, load goes rear
        ax < 0 -> braking, load goes front

        ay > 0 -> acceleration to the left, load goes right
    */
    double ax_mps2 = 0.0;
    double ay_mps2 = 0.0;

    /*
        Bicycle / rack steering angle [rad].

        The allocator receives only this single steering command.
        It converts it internally to real left/right front wheel angles
        using the fitted anti-Ackermann relation.
    */
    double delta_bicycle_rad = 0.0;

    /*
        Previous total torque actually published by allocator [Nm],
        wheel-side, signed.

        Used for normalized total-torque rate limiting.

        M_dot_up/down are dimensionless total-torque rates [1/s]:
            max_total_step = M_dot * model.drivetrain.max_motor_torque * dt

        Because the final allocator limiter uses one global scale for all
        wheels, the rate limit is computed on total torque, not per wheel.
    */
    double previous_total_limited_torque_Nm = 0.0;
    bool previous_total_limited_torque_valid = false;

    /*
        Safety / finished / hard stop paths may bypass the rate limiter and
        publish zero torque immediately.
    */
    bool bypass_torque_rate_limiter = false;
};

struct TorqueAllocationResult
{
    TorqueAllocationMode mode = TorqueAllocationMode::DV_QP;

    WheelValues Fz_N;

    /*
        Estymacja tylko do friction pre-limitera.
        To NIE jest pełny tire model.
    */
    WheelValues slip_angle_rad;
    WheelValues estimated_Fy_N;

    WheelValues torque_base_Nm;
    WheelValues torque_after_tv_Nm;
    WheelValues torque_limited_Nm;

    WheelValues max_abs_torque_from_friction_Nm;
    WheelValues max_abs_torque_after_all_limits_Nm;

    /*
        Final limiter debug.

        hard_limit_scale is always the actually applicable mechanical/friction
        scale in [0, 1]. It must never amplify torque.
    */
    double hard_limit_scale = 1.0;

    double input_total_torque_cmd_Nm = 0.0;
    double rate_limited_total_torque_cmd_Nm = 0.0;

    double previous_total_limited_torque_Nm = 0.0;
    double total_torque_rate_scale_min = 0.0;
    double total_torque_rate_scale_max = 1.0;
    double total_torque_rate_limited_scale = 1.0;

    double normalized_M_dot_up = 0.0;
    double normalized_M_dot_down = 0.0;
    double max_total_torque_step_up_Nm = 0.0;
    double max_total_torque_step_down_Nm = 0.0;

    bool torque_rate_limited = false;
    bool torque_rate_forced_over_hard_limit = false;
    bool torque_rate_limiter_bypassed = false;

    double global_scale = 1.0;
    bool limited = false;

    /*
        Final per-wheel engine-side limiter.

        This limiter is applied at the very end and uses one global scale for
        the whole wheel-torque vector, so it preserves the balance produced by
        base allocation + TV + previous limiters.

        Limits are configured on engine side per wheel:
            model.drivetrain.wheel_max_torque_engine_drive_Nm
            model.drivetrain.wheel_max_torque_engine_brake_Nm

        Converted to wheel side by gear_ratio.
    */
    double final_engine_per_wheel_limit_scale = 1.0;
    bool final_engine_per_wheel_limited = false;

    double wheel_drive_limit_from_engine_Nm = 0.0;
    double wheel_brake_limit_from_engine_Nm = 0.0;

    double vx_raw_mps = 0.0;
    double vx_for_slip_limiter_mps = 0.0;

    double requested_longitudinal_force_N = 0.0;
    double achieved_longitudinal_force_before_limit_N = 0.0;
    double achieved_longitudinal_force_after_limit_N = 0.0;
    double longitudinal_force_error_before_limit_N = 0.0;
    double longitudinal_force_error_after_limit_N = 0.0;

    double requested_yaw_moment_Nm = 0.0;
    double base_yaw_moment_Nm = 0.0;
    double tv_yaw_moment_target_Nm = 0.0;

    /*
        Real front wheel steering angles used internally by allocation,
        obtained from delta_bicycle_rad using anti-Ackermann fit.
    */
    double delta_left_rad = 0.0;
    double delta_right_rad = 0.0;

    double achieved_yaw_moment_before_limit_Nm = 0.0;
    double achieved_yaw_moment_after_limit_Nm = 0.0;
    double yaw_moment_error_before_limit_Nm = 0.0;
    double yaw_moment_error_after_limit_Nm = 0.0;

    double total_torque_after_tv_Nm = 0.0;
    double total_torque_limited_Nm = 0.0;

    /*
        DV_AXLE:
            tau = tau_base + [dTauF, -dTauF, dTauR, -dTauR]

        DV_QP:
            pola debugowe, liczone jako equivalent delta względem base.
    */
    double delta_front_tv_Nm = 0.0;
    double delta_rear_tv_Nm = 0.0;

    /*
        JACA:
            tau = tau_base + [dTauJ, -dTauJ, dTauJ, -dTauJ]
    */
    double delta_jaca_tv_Nm = 0.0;

    bool qp_solved = false;
    bool used_fallback = false;
};

