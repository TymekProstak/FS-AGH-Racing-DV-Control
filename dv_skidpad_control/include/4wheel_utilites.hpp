inline double clampLocal(
    const double x,
    const double lo,
    const double hi
)
{
    return std::max(lo, std::min(x, hi));
}

inline double safeAbs(
    const double x,
    const double eps = 1.0e-9
)
{
    return std::max(std::abs(x), eps);
}

inline const char* torqueAllocationModeToString(
    const TorqueAllocationMode mode
)
{
    switch (mode)
    {
        case TorqueAllocationMode::DV_QP:
            return "DV_QP";

        case TorqueAllocationMode::DV_AXLE:
            return "DV_AXLE";

        case TorqueAllocationMode::JACA:
            return "JACA";
    }

    return "UNKNOWN";
}

inline double speedForSlipAndLimiterMps(
    const double vx_mps
)
{
    constexpr double VX_MIN_FOR_SLIP_LIMITER_MPS =
        2.0;

    /*
        There is no reverse-driving mode here.

        This speed is used only for slip/Fy/friction-limiter estimation.
        Never preserve a negative vx sign.  Around standstill, vx can be
        slightly negative from noise even though the car is not reversing.
    */
    if (!std::isfinite(vx_mps))
    {
        return VX_MIN_FOR_SLIP_LIMITER_MPS;
    }

    return std::max(
        vx_mps,
        VX_MIN_FOR_SLIP_LIMITER_MPS
    );
}

inline bool paramFlag(
    const ParamBank& P,
    const std::string& key
)
{
    return P.get(key) > 0.5;
}

inline double getTrackWidthM(
    const ParamBank& P
)
{
    /*
        Common vehicle track width used by:
          - wheel-centre kinematics,
          - normal-load estimation,
          - yaw-moment calculation,
          - all torque-allocation modes.

        Keep the JACA-specific copy in JSON for compatibility with older code,
        but the allocator uses the common body geometry value.
    */
    return P.get("model.body.track_width");
}

inline double getTireRadiusM(
    const ParamBank& P
)
{
    return P.get("model.tire.R_tire");
}

inline double getGearRatio(
    const ParamBank& P
)
{
    return P.get("model.drivetrain.gear_ratio");
}

inline double getWheelDriveLimitFromEngineNm(
    const ParamBank& P
)
{
    const double limit_engine_Nm =
        P.get("model.drivetrain.wheel_max_torque_engine_drive_Nm");

    const double gear_ratio =
        getGearRatio(P);

    return
        std::max(0.0, limit_engine_Nm)
        * std::max(0.0, gear_ratio);
}

inline double getWheelBrakeLimitFromEngineNm(
    const ParamBank& P
)
{
    const double limit_engine_Nm =
        P.get("model.drivetrain.wheel_max_torque_engine_brake_Nm");

    const double gear_ratio =
        getGearRatio(P);

    return
        std::max(0.0, limit_engine_Nm)
        * std::max(0.0, gear_ratio);
}

inline double wheelTorqueToFxN(
    const ParamBank& P,
    const double torque_Nm
)
{
    return torque_Nm / safeAbs(getTireRadiusM(P));
}

inline double FxToWheelTorqueNm(
    const ParamBank& P,
    const double Fx_N
)
{
    return Fx_N * getTireRadiusM(P);
}

inline WheelValues scaleWheelValues(
    const WheelValues& in,
    const double scale
)
{
    WheelValues out;

    out.FL = in.FL * scale;
    out.FR = in.FR * scale;
    out.RL = in.RL * scale;
    out.RR = in.RR * scale;

    return out;
}

inline WheelValues minWheelValues(
    const WheelValues& a,
    const WheelValues& b
)
{
    WheelValues out;

    out.FL = std::min(a.FL, b.FL);
    out.FR = std::min(a.FR, b.FR);
    out.RL = std::min(a.RL, b.RL);
    out.RR = std::min(a.RR, b.RR);

    return out;
}

inline double sumWheelValues(
    const WheelValues& v
)
{
    return
        v.FL
        + v.FR
        + v.RL
        + v.RR;
}

inline double computeLongitudinalBodyForceFromWheelTorquesN(
    const ParamBank& P,
    const WheelValues& torque_Nm,
    const double delta_left_rad,
    const double delta_right_rad
)
{
    const double R_tire =
        getTireRadiusM(P);

    const double Fx_FL =
        torque_Nm.FL / safeAbs(R_tire);

    const double Fx_FR =
        torque_Nm.FR / safeAbs(R_tire);

    const double Fx_RL =
        torque_Nm.RL / safeAbs(R_tire);

    const double Fx_RR =
        torque_Nm.RR / safeAbs(R_tire);

    return
        Fx_FL * std::cos(delta_left_rad)
        + Fx_FR * std::cos(delta_right_rad)
        + Fx_RL
        + Fx_RR;
}

// ============================================================================
//                      ANTI-ACKERMANN STEERING FIT
// ============================================================================
//
// The allocator receives one bicycle/rack angle d.
// It converts d to real front-left and front-right wheel angles using the same
// fitted relation as the vehicle model:
//
//      delta_right = d + 0.09298947992255 * d^2 + 0.00324282679268
//      delta_left  = d - 0.09298947992255 * d^2 - 0.00324282679268
//
// Valid fitting range: about +/- 0.4528 rad.
// For max_steer = 0.38 rad this is inside the fitted range.
//
// ============================================================================

struct SteeringAngles
{
    double delta_left_rad = 0.0;
    double delta_right_rad = 0.0;
};

inline SteeringAngles computeAntiAckermannSteeringAngles(
    const double delta_bicycle_rad,
    const ParamBank& P
)
{
    (void)P;

    const double d =
        delta_bicycle_rad;

    constexpr double ACKERMANN_QUAD_COEFF =
        9.298947992255e-02;

    constexpr double TOE_OFFSET_RAD =
        3.242826792680e-03;

    const double d2 =
        d * d;

    SteeringAngles out;

    out.delta_left_rad =
        d
        - ACKERMANN_QUAD_COEFF * d2
        - TOE_OFFSET_RAD;

    out.delta_right_rad =
        d
        + ACKERMANN_QUAD_COEFF * d2
        + TOE_OFFSET_RAD;

    return out;
}

// ============================================================================
//                      SLIP ANGLE ESTIMATE LIKE TIRE MODEL
// ============================================================================
//
// Liczenie jak w tire modelu:
//
//      1. velocity at wheel center
//      2. rotate velocity into wheel frame
//      3. alpha = -atan2(vy_local, vx_local)
//
// Używa tylko:
//      model.body.l_f
//      model.body.l_r
//      model.body.track_width
//
// ============================================================================

inline double safeVxSignedForSlip(
    const double vx_mps
)
{
    constexpr double EPS_VX =
        1.0e-4;

    /*
        There is no reverse-driving mode in this controller.

        This helper is used only as atan2 denominator in the slip estimator.
        Therefore it must never return a negative value.  A tiny negative vx
        from odometry/encoder noise near standstill must not flip the slip
        angle by pi and saturate the friction ellipse.
    */
    if (!std::isfinite(vx_mps))
    {
        return EPS_VX;
    }

    return std::max(
        vx_mps,
        EPS_VX
    );
}

inline void rotateVelocityToWheelFrame(
    const double wheel_angle_rad,
    double& vx_mps,
    double& vy_mps
)
{
    const double c =
        std::cos(wheel_angle_rad);

    const double s =
        std::sin(wheel_angle_rad);

    const double vx0 =
        vx_mps;

    const double vy0 =
        vy_mps;

    /*
        Same transform as tire model:

            vx_local =  c * vx + s * vy
            vy_local = -s * vx + c * vy
    */

    vx_mps =
        c * vx0
        + s * vy0;

    vy_mps =
        -s * vx0
        + c * vy0;
}

inline WheelValues estimateWheelSlipAnglesLikeTireModelRad(
    const ParamBank& P,
    const double vx_mps,
    const double vy_mps,
    const double yaw_rate_radps,
    const double delta_left_rad,
    const double delta_right_rad
)
{
    const double l_f =
        P.get("model.body.l_f");

    const double l_r =
        P.get("model.body.l_r");

    const double half_track =
        0.5 * getTrackWidthM(P);

    /*
        Body frame:
            x forward
            y left

        Wheel positions:
            FL: x = +l_f, y = +track/2
            FR: x = +l_f, y = -track/2
            RL: x = -l_r, y = +track/2
            RR: x = -l_r, y = -track/2

        Velocity:
            vx_w = vx - yaw_rate * y_w
            vy_w = vy + yaw_rate * x_w
    */

    double vx_fl =
        vx_mps
        - yaw_rate_radps * half_track;

    double vy_fl =
        vy_mps
        + yaw_rate_radps * l_f;

    double vx_fr =
        vx_mps
        + yaw_rate_radps * half_track;

    double vy_fr =
        vy_mps
        + yaw_rate_radps * l_f;

    double vx_rl =
        vx_mps
        - yaw_rate_radps * half_track;

    double vy_rl =
        vy_mps
        - yaw_rate_radps * l_r;

    double vx_rr =
        vx_mps
        + yaw_rate_radps * half_track;

    double vy_rr =
        vy_mps
        - yaw_rate_radps * l_r;

    rotateVelocityToWheelFrame(
        delta_left_rad,
        vx_fl,
        vy_fl
    );

    rotateVelocityToWheelFrame(
        delta_right_rad,
        vx_fr,
        vy_fr
    );

    rotateVelocityToWheelFrame(
        0.0,
        vx_rl,
        vy_rl
    );

    rotateVelocityToWheelFrame(
        0.0,
        vx_rr,
        vy_rr
    );

    WheelValues alpha;

    alpha.FL =
        -std::atan2(
            vy_fl,
            safeVxSignedForSlip(vx_fl)
        );

    alpha.FR =
        -std::atan2(
            vy_fr,
            safeVxSignedForSlip(vx_fr)
        );

    alpha.RL =
        -std::atan2(
            vy_rl,
            safeVxSignedForSlip(vx_rl)
        );

    alpha.RR =
        -std::atan2(
            vy_rr,
            safeVxSignedForSlip(vx_rr)
        );

    constexpr double PI =
        3.14159265358979323846;

    const double alpha_min =
        -PI / 2.0 + 0.3;

    const double alpha_max =
        PI / 2.0 - 0.3;

    alpha.FL = clampLocal(alpha.FL, alpha_min, alpha_max);
    alpha.FR = clampLocal(alpha.FR, alpha_min, alpha_max);
    alpha.RL = clampLocal(alpha.RL, alpha_min, alpha_max);
    alpha.RR = clampLocal(alpha.RR, alpha_min, alpha_max);

    return alpha;
}

// ============================================================================
//                      NORMAL LOAD ESTIMATION FOR CONTROL
// ============================================================================
//
// Quasi-static wheel normal-load model consistent with dv_control.
//
// Required parameters:
//      model.body.m
//      model.body.g
//      model.body.l_f
//      model.body.l_r
//      model.body.h_cg
//      model.body.track_width
//      model.body.h1_roll
//      model.body.h2_roll
//      model.body.lambda_phi_elastic_lateral
//
// Roll convention:
//      h1_roll -> front roll-centre height [m]
//      h2_roll -> rear  roll-centre height [m]
//      lambda_phi_elastic_lateral -> front share of elastic roll moment [0, 1]
//
// ay > 0 means acceleration to the left, therefore load transfers to the
// right-hand wheels.
//
// The lateral transfer is split into:
//
//   1. geometric/direct component at each axle roll centre,
//   2. elastic component caused by the CG-to-roll-axis lever arm.
//
// With:
//      m_f = m*l_r/L
//      m_r = m*l_f/L
//
// the elastic roll-moment coefficient is:
//
//      H_el = m_f*(h_cg - h1_roll)
//           + m_r*(h_cg - h2_roll)
//
// The load transferred from the left wheel to the right wheel at each axle is:
//
//      dF_front = ay/track *
//          (m_f*h1_roll + lambda_phi*H_el)
//
//      dF_rear  = ay/track *
//          (m_r*h2_roll + (1-lambda_phi)*H_el)
//
// Wheel loads use +/- dF directly:
//
//      FL = Fz_front/2 - dF_front
//      FR = Fz_front/2 + dF_front
//      RL = Fz_rear /2 - dF_rear
//      RR = Fz_rear /2 + dF_rear
//
// This convention gives the correct total roll-moment equilibrium:
//
//      track*dF_front + track*dF_rear = m*ay*h_cg
//
// Optional aero load:
//      model.resistance.Cl1 * vx^2 -> front axle
//      model.resistance.Cl2 * vx^2 -> rear axle
// when model.resistance.use_aero == true.
//
// ============================================================================

inline WheelValues estimateWheelNormalLoadsN(
    const ParamBank& P,
    const double ax_relaxed_mps2,
    const double ay_relaxed_mps2,
    const double vx_mps = 0.0
)
{
    dv_control_common::WheelLoadModelParameters model;

    model.mass_kg = P.get("model.body.m");
    model.gravity_mps2 = P.get("model.body.g");
    model.lf_m = P.get("model.body.l_f");
    model.lr_m = P.get("model.body.l_r");
    model.h_cg_m = P.get("model.body.h_cg");
    model.track_front_m = getTrackWidthM(P);
    model.track_rear_m = getTrackWidthM(P);
    model.h_roll_center_front_m = P.get("model.body.h1_roll");
    model.h_roll_center_rear_m = P.get("model.body.h2_roll");
    model.lambda_elastic_front =
        P.get("model.body.lambda_phi_elastic_lateral");
    model.minimum_wheel_load_N =
        P.get("model.mass_transfer.minimum_wheel_load_N");

    double front_aero_N = 0.0;
    double rear_aero_N = 0.0;

    if (paramFlag(P, "model.resistance.use_aero"))
    {
        const double speed_mps =
            std::max(
                0.0,
                std::isfinite(vx_mps) ? vx_mps : 0.0
            );

        front_aero_N =
            P.get("model.resistance.Cl1") * speed_mps * speed_mps;

        rear_aero_N =
            P.get("model.resistance.Cl2") * speed_mps * speed_mps;
    }

    const dv_control_common::WheelLoadsN shared =
        dv_control_common::computeWheelLoadsN(
            model,
            ax_relaxed_mps2,
            ay_relaxed_mps2,
            front_aero_N,
            rear_aero_N
        );

    WheelValues out;
    out.FL = shared.FL;
    out.FR = shared.FR;
    out.RL = shared.RL;
    out.RR = shared.RR;
    return out;
}

// ============================================================================
//                      ESTIMATED FY FROM SLIP ANGLES
// ============================================================================
//
// Uproszczony lateral estimate do friction pre-limitera:
//
//      Fy = D * Fz * sin(C * atan(B * alpha))
//
// Parametry:
//      model.body.Bf
//      model.body.Cf
//      model.body.Df
//      model.body.Br
//      model.body.Cr
//      model.body.Dr
//
// ============================================================================

inline double estimateLateralForceFromSlipAngleN(
    const double alpha_rad,
    const double Fz_N,
    const double B,
    const double C,
    const double D
)
{
    return
        D
        * Fz_N
        * std::sin(
            C * std::atan(B * alpha_rad)
        );
}

inline WheelValues estimateWheelLateralForcesFromSlipAnglesN(
    const ParamBank& P,
    const WheelValues& slip_angle_rad,
    const WheelValues& Fz_N
)
{
    const double Bf =
        P.get("model.body.Bf");

    const double Cf =
        P.get("model.body.Cf");

    const double Df =
        P.get("model.body.Df");

    const double Br =
        P.get("model.body.Br");

    const double Cr =
        P.get("model.body.Cr");

    const double Dr =
        P.get("model.body.Dr");

    WheelValues Fy;

    Fy.FL =
        estimateLateralForceFromSlipAngleN(
            slip_angle_rad.FL,
            Fz_N.FL,
            Bf,
            Cf,
            Df
        );

    Fy.FR =
        estimateLateralForceFromSlipAngleN(
            slip_angle_rad.FR,
            Fz_N.FR,
            Bf,
            Cf,
            Df
        );

    Fy.RL =
        estimateLateralForceFromSlipAngleN(
            slip_angle_rad.RL,
            Fz_N.RL,
            Br,
            Cr,
            Dr
        );

    Fy.RR =
        estimateLateralForceFromSlipAngleN(
            slip_angle_rad.RR,
            Fz_N.RR,
            Br,
            Cr,
            Dr
        );

    return Fy;
}

